import Foundation

/// Transport-neutral types shared by the native client and the protocol tests.
nonisolated enum AgentConnectionState: Equatable, Sendable {
    case idle
    case connecting
    case ready
    case reconnecting(attempt: Int)
    case failed(String)

    var isReady: Bool { self == .ready }
}

nonisolated struct AgentHistoryMessage: Codable, Equatable, Sendable {
    enum Role: String, Codable, Sendable { case user, assistant }
    var role: Role
    var content: String

    init(role: Role, content: String) {
        self.role = role
        self.content = content
    }
}

nonisolated struct AgentLatency: Equatable, Sendable {
    let transcription: Double?
    let firstText: Double?
    /// Provider total measures first AUDIO, not first text displayed by this app.
    let total: Double?
}

nonisolated enum AgentEvent: Equatable, Sendable {
    case userStartedSpeaking
    case userTranscript(String)
    case assistantText(String)
    case thinking
    case responseFinished
    case latency(AgentLatency)
    case warning(String)
    /// A WebSocket send succeeded, but the provider did not accept the input.
    case inputRejected(String)
}

nonisolated enum AgentServerMessage: Equatable, Sendable {
    case welcome
    case settingsApplied
    case event(AgentEvent)
    case error(code: String)
    case warning(code: String)
    case unknown
}

nonisolated enum AgentClientError: LocalizedError, Equatable, Sendable {
    case missingKey
    case emptyPrompt
    case promptTooLong
    case notReady
    case emptyInput
    case inputTooLong
    case invalidMessage
    case sendUncertain
    case audioDrainTimeout

    var errorDescription: String? {
        switch self {
        case .missingKey: return "Add your Deepgram API key in Settings before starting."
        case .emptyPrompt: return "Add interview context before starting."
        case .promptTooLong: return "Interview context exceeds Deepgram's 25,000-character prompt limit. Shorten the resume or job description."
        case .notReady: return "Wait for the Deepgram connection to be ready, then try again."
        case .emptyInput: return "Enter a question first."
        case .inputTooLong: return "This question is too long. Use 8,000 characters or fewer."
        case .invalidMessage: return "Deepgram returned an unreadable message. Restart the session."
        case .sendUncertain: return "The connection changed while sending. Check the transcript before resending the question."
        case .audioDrainTimeout: return "Audio is still reaching Deepgram. Keep the microphone muted, wait a moment, then tap Answer now again."
        }
    }
}

nonisolated struct AgentFailure: Equatable, Sendable {
    let message: String
    let canRetry: Bool
}

nonisolated enum DeepgramProtocol {
    static let endpoint = URL(string: "wss://agent.deepgram.com/v1/agent/converse")!
    static let sampleRate = 16_000
    static let maximumPromptCharacters = 25_000
    static let maximumInputCharacters = 8_000
    static let maximumHistoryCharacters = 24_000
    static let maximumHistoryMessages = 32
    static let maximumAutomaticRetries = 3

    /// No LLM endpoint or LLM credential is sent: both providers are managed and
    /// billed by Deepgram. TTS is generated by the provider but discarded locally.
    static func settings(prompt: String, history: [AgentHistoryMessage]) throws -> String {
        guard !prompt.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            throw AgentClientError.emptyPrompt
        }
        guard prompt.count <= maximumPromptCharacters else { throw AgentClientError.promptTooLong }
        let think: [[String: Any]] = [
            ["provider": ["type": "open_ai", "model": "gpt-4.1-mini", "temperature": 0.3],
             "prompt": prompt],
            ["provider": ["type": "google", "model": "gemini-2.5-flash", "temperature": 0.3],
             "prompt": prompt]
        ]
        let body: [String: Any] = [
            "type": "Settings",
            "mip_opt_out": true,
            "audio": [
                "input": ["encoding": "linear16", "sample_rate": sampleRate],
                "output": ["encoding": "linear16", "sample_rate": 24_000, "container": "none"]
            ],
            "agent": [
                "listen": ["provider": [
                    "type": "deepgram", "version": "v2", "model": "flux-general-en",
                    "eot_threshold": 0.7, "eager_eot_threshold": 0.5, "eot_timeout_ms": 5_000
                ]],
                "think": think,
                "speak": ["provider": ["type": "deepgram", "version": "v2", "model": "flux-kit-en"]],
                "context": ["messages": boundedHistory(history).map {
                    ["type": "History", "role": $0.role.rawValue, "content": $0.content]
                }]
            ]
        ]
        return try json(body)
    }

    /// Retain the newest turns within a strict bound. This is a local history
    /// budget, not a claim about the provider's context window.
    static func boundedHistory(_ history: [AgentHistoryMessage]) -> [AgentHistoryMessage] {
        var result: [AgentHistoryMessage] = []
        var remaining = maximumHistoryCharacters
        for message in history.reversed() {
            guard result.count < maximumHistoryMessages, remaining > 0 else { break }
            let text = message.content.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !text.isEmpty else { continue }
            let clipped = String(text.prefix(min(4_000, remaining)))
            result.append(AgentHistoryMessage(role: message.role, content: clipped))
            remaining -= clipped.count
        }
        return result.reversed()
    }

    static func injectUser(_ text: String) throws -> String {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { throw AgentClientError.emptyInput }
        guard trimmed.count <= maximumInputCharacters else { throw AgentClientError.inputTooLong }
        return try json(["type": "InjectUserMessage", "content": trimmed])
    }

    static let keepAlive = "{\"type\":\"KeepAlive\"}"
    static let forceEndTurn = "{\"type\":\"ForceEndTurn\"}"

    static func decode(_ text: String) throws -> AgentServerMessage {
        guard text.utf8.count <= 1_048_576,
              let data = text.data(using: .utf8),
              let message = try? JSONDecoder().decode(WireMessage.self, from: data) else {
            throw AgentClientError.invalidMessage
        }
        switch message.type {
        case "Welcome": return .welcome
        case "SettingsApplied": return .settingsApplied
        case "UserStartedSpeaking": return .event(.userStartedSpeaking)
        case "AgentThinking": return .event(.thinking)
        case "AgentAudioDone": return .event(.responseFinished)
        case "InjectionRefused":
            return .event(.inputRejected("Deepgram did not accept the typed question. Wait for the current speaker or answer to finish, then submit it again."))
        case "ConversationText":
            guard let content = message.content, !content.isEmpty else { return .unknown }
            switch message.role {
            case "user": return .event(.userTranscript(content))
            case "assistant": return .event(.assistantText(content))
            default: return .unknown
            }
        case "LatencyReport":
            return .event(.latency(AgentLatency(
                transcription: validLatency(message.sttLatency),
                firstText: validLatency(message.textLatency),
                total: validLatency(message.totalLatency)
            )))
        case "Error": return .error(code: message.code ?? "UNKNOWN")
        case "Warning":
            // Some provider versions report this race as a warning instead of
            // InjectionRefused. Do not mistake transport delivery for acceptance.
            if message.code == "INJECT_USER_MESSAGE_DURING_USER_SPEECH" {
                return .event(.inputRejected("Deepgram did not accept the typed question while speech was in progress. Wait for the speaker to finish, then submit it again."))
            }
            return .warning(code: message.code ?? "UNKNOWN")
        default: return .unknown // Forward-compatible with new provider events.
        }
    }

    /// Never surface provider descriptions: upstream errors can contain request
    /// payloads or credentials. Only fixed local messages reach the UI.
    static func failure(code: String, httpStatus: Int? = nil) -> AgentFailure {
        if httpStatus == 401 || httpStatus == 403 {
            return .init(message: "Deepgram rejected this API key. Check the key and its project permissions in Settings.", canRetry: false)
        }
        if httpStatus == 402 || ["INSUFFICIENT_CREDITS", "PAYMENT_REQUIRED", "INSUFFICIENT_BALANCE"].contains(code) {
            return .init(message: "Deepgram needs available credit on this key's project. Check the Deepgram account balance.", canRetry: false)
        }
        if httpStatus == 429 || code == "TOO_MANY_REQUESTS" {
            return .init(message: "Deepgram's connection limit was reached. Close other sessions and try again shortly.", canRetry: false)
        }
        switch code {
        case "INVALID_AUTH", "INVALID_AUTHENTICATION", "UNAUTHORIZED", "FORBIDDEN":
            return .init(message: "Deepgram rejected this API key. Check its project and permissions in Settings.", canRetry: false)
        case "INVALID_SETTINGS", "UNPARSABLE_CLIENT_MESSAGE", "NON_SETTINGS_MESSAGE_BEFORE_SETTINGS", "SETTINGS_ALREADY_APPLIED":
            return .init(message: "Deepgram rejected the session configuration. Update the app or check model availability before retrying.", canRetry: false)
        case "USER_AUDIO_FORMAT":
            return .init(message: "The microphone audio format was rejected. Stop and restart the session.", canRetry: false)
        case "FAILED_TO_THINK":
            return .init(message: "Deepgram could not generate an answer with either configured model. Check project access and credit, then retry.", canRetry: false)
        case "MAXIMUM_SESSION_LENGTH_REACHED":
            return .init(message: "Deepgram's session limit was reached. Reconnecting with your interview context.", canRetry: true)
        case "CONNECT_TIMEOUT":
            return .init(message: "Deepgram did not finish connecting in time. Check your internet connection.", canRetry: true)
        case "HEARTBEAT_TIMEOUT":
            return .init(message: "The Deepgram connection stopped responding. Reconnecting.", canRetry: true)
        case "AUDIO_SEND_TIMEOUT":
            return .init(message: "Audio could not reach Deepgram fast enough. Reconnecting; repeat the unfinished question when ready.", canRetry: true)
        default:
            return .init(message: "The Deepgram connection was interrupted. Reconnecting with your interview context.", canRetry: true)
        }
    }

    static func warning(code: String) -> String {
        switch code {
        case "THINK_REQUEST_FAILED": return "The primary model is unavailable. Deepgram is trying the fallback model."
        case "MAXIMUM_SESSION_LENGTH_APPROACHING": return "This connection is nearing Deepgram's session limit. It will reconnect between turns."
        case "INJECT_USER_MESSAGE_DURING_USER_SPEECH": return "Wait for the speaker to finish, then submit the typed question again."
        default: return "Deepgram reported a temporary issue. The session is still connected."
        }
    }

    private static func validLatency(_ value: Double?) -> Double? {
        guard let value, value.isFinite, value >= 0 else { return nil }
        return value
    }

    private static func json(_ object: [String: Any]) throws -> String {
        let data = try JSONSerialization.data(withJSONObject: object, options: [.sortedKeys])
        guard let text = String(data: data, encoding: .utf8) else { throw AgentClientError.invalidMessage }
        return text
    }

    private struct WireMessage: Decodable {
        let type: String
        let role: String?
        let content: String?
        let code: String?
        let sttLatency: Double?
        let textLatency: Double?
        let totalLatency: Double?

        enum CodingKeys: String, CodingKey {
            case type, role, content, code
            case sttLatency = "stt_latency"
            case textLatency = "ttt_text_latency"
            case totalLatency = "total_latency"
        }
    }
}

/// A single, bounded PCM queue bridges the real-time audio thread to the socket.
/// No tasks are created per audio buffer and old audio is never replayed after a
/// reconnect. Overflow is reported rather than allowed to become growing delay.
nonisolated final class AgentAudioQueue: @unchecked Sendable {
    private let lock = NSLock()
    private var frames: [Data] = []
    private var byteCount = 0
    private var enabled = false
    private var dropped = false
    let maximumBytes: Int
    private var continuation: AsyncStream<Void>.Continuation?

    init(maximumBytes: Int = 16_000) {
        self.maximumBytes = max(2, maximumBytes)
    }

    /// Every connection gets a fresh stream. Reusing an AsyncStream after its
    /// consumer was cancelled would leave reconnection permanently silent.
    func start() -> AsyncStream<Void> {
        let pair = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
        let previous = lock.withLock {
            let old = continuation
            continuation = pair.continuation
            enabled = true
            frames.removeAll(keepingCapacity: true)
            byteCount = 0
            dropped = false
            return old
        }
        previous?.finish()
        return pair.stream
    }

    func stop() {
        let previous = lock.withLock {
            let old = continuation
            continuation = nil
            enabled = false
            frames.removeAll(keepingCapacity: true)
            byteCount = 0
            dropped = false
            return old
        }
        previous?.finish()
    }

    func push(_ data: Data) {
        guard !data.isEmpty else { return }
        let signal = lock.withLock { () -> AsyncStream<Void>.Continuation? in
            guard enabled else { return nil }
            guard data.count <= maximumBytes, data.count.isMultiple(of: 2) else {
                dropped = true
                return continuation
            }
            while byteCount + data.count > maximumBytes, !frames.isEmpty {
                byteCount -= frames.removeFirst().count
                dropped = true
            }
            frames.append(data)
            byteCount += data.count
            return continuation
        }
        signal?.yield(())
    }

    func pop() -> Data? {
        lock.withLock {
            guard enabled, !frames.isEmpty else { return nil }
            let frame = frames.removeFirst()
            byteCount -= frame.count
            return frame
        }
    }

    func takeDroppedFlag() -> Bool {
        lock.withLock {
            let result = dropped
            dropped = false
            return result
        }
    }

    var bufferedBytes: Int { lock.withLock { byteCount } }

    deinit { continuation?.finish() }
}
